import {readFile,mkdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_ENTRY?pathToFileURL(process.env.PLAYWRIGHT_ENTRY).href:'playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.TEST_BROWSER||undefined});
try{
  const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await mkdir('tmp/qa',{recursive:true});
  await page.goto(process.env.TEST_URL||'http://127.0.0.1:4173/');
  await page.getByRole('button',{name:'Serbest laboratuvar',exact:true}).click();
  await page.locator('#terminal-command').fill('mkdir keep; cd keep; echo saved > a.txt; session=214; arr=(a b); f(){ echo hello; }');
  await page.locator('#terminal-command').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#cwd-label')?.textContent==='/home/ogrenci/keep');
  await page.locator('[data-tree="lab"][data-path="/home/ogrenci/keep"]').click();
  await page.locator('[data-tree="lab"][data-path="/home/ogrenci/keep/a.txt"]').click();
  await page.locator('.cm-content').fill('unsaved backup draft');
  const downloading=page.waitForEvent('download');await page.locator('.topbar [data-action="backup"]').click();
  await (await downloading).saveAs('tmp/qa/backup.json');
  const backup=JSON.parse(await readFile('tmp/qa/backup.json','utf8'));
  assert.equal(backup.preferences.labPath,'/home/ogrenci/keep/a.txt');
  assert.equal(backup.preferences.fileDrafts['/home/ogrenci/keep/a.txt'],'unsaved backup draft');
  assert.equal(backup.workspace.entries.find(x=>x.path==='/home/ogrenci/keep/a.txt').content,'saved\n');
  await page.locator('[data-action="reset-lab"]').click();
  await page.locator('[data-action="confirm-reset-lab"]').click();
  await page.waitForFunction(()=>document.querySelector('#editor-filename')?.textContent==='/home/ogrenci/calisma.sh');
  assert.equal(await page.locator('[data-tree="lab"][data-path="/home/ogrenci/keep"]').count(),0);
  assert.ok(!(await page.locator('.cm-content').innerText()).includes('unsaved backup draft'));
  await page.locator('[data-action="help"]').click();
  await page.locator('#import-file').setInputFiles('tmp/qa/backup.json');
  await page.locator('#confirm-import').click();
  await page.getByRole('button',{name:'Serbest laboratuvar',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#cwd-label')?.textContent==='/home/ogrenci/keep');
  assert.equal(await page.locator('#editor-filename').innerText(),'/home/ogrenci/keep/a.txt');
  assert.equal(await page.locator('.cm-content').innerText(),'unsaved backup draft');
  await page.locator('#terminal-command').fill('echo "$session ${arr[1]}"; f; cat a.txt');await page.locator('#terminal-command').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#terminal-body')?.textContent.includes('214 b\nhello\nsaved'));
  console.log('PASS: root URL, backup, reset and import restore files, drafts, cwd, variables, arrays and functions');
  await page.locator('#lab-language').selectOption('c');
  await page.locator('.cm-content').fill('int main(void){for(;;){} return 0;}');
  await page.locator('[data-action="run"]').click();
  await page.getByText('Süre sınırı aşıldı. Sonsuz döngüyü veya eksik girdiyi kontrol et.',{exact:true}).waitFor({timeout:60000});
  await page.locator('.cm-content').fill('#include <stdio.h>\nint main(void){puts("recovered");return 0;}');
  await page.locator('[data-action="run"]').click();
  await page.waitForFunction(()=>document.querySelector('.output-stdout')?.textContent==='recovered\n');
  assert.deepEqual(errors,[]);
  console.log('PASS: C infinite loop timeout and recovery without page reload');
}finally{await browser.close();}
